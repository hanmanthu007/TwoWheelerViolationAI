from datetime import datetime
import os

# =========================================================
# STATUTORY MOTOR VEHICLE ACT 2019 VERIFIED PROVISIONS
# =========================================================
FINE_STRUCTURE = {
    "TRIPLE_RIDING": 1000,       # Section 128 read with Sec 194C MV Act
    "OVERLOADING": 2000,         # Section 194A MV Act (>3 riders)
    "NO_HELMET_PER_RIDER": 1000  # Section 129 read with Sec 194D MV Act (Per rider)
}


def calculate_and_generate_challan(
    plate_number="UNKNOWN",
    person_count=3,
    without_helmet_count=3,
    output_image_path="final_violation_output.jpg",
    save_receipt=True,
    generate_pdf=True,
    location="Surveillance Sector #04 - Junction Camera #02",
    plate_crop_path=None
):
    """
    Computes traffic violation fines, saves a demonstration text receipt,
    and automatically issues an official PDF report via pdf_challan_generator.
    """
    challan_id = f"DEMO-ECH-{datetime.now().strftime('%Y%m%d-%H%M%S')}"
    timestamp = datetime.now().strftime("%d-%b-%Y %I:%M:%S %p")
    
    violations_detected = []
    total_fine = 0

    # 1. Overloading / Triple Riding Assessment (Sec 128/194C & 194A)
    if person_count == 3:
        fine_amount = FINE_STRUCTURE["TRIPLE_RIDING"]
        violations_detected.append(("Triple Riding on Two-Wheeler (Sec 128/194C M.V. Act)", fine_amount))
        total_fine += fine_amount
    elif person_count > 3:
        fine_amount = FINE_STRUCTURE["OVERLOADING"]
        violations_detected.append((f"Dangerous Overloading ({person_count} Persons) - Sec 194A M.V. Act", fine_amount))
        total_fine += fine_amount

    # 2. Helmet Violation Assessment (Sec 129/194D)
    if without_helmet_count > 0:
        fine_amount = without_helmet_count * FINE_STRUCTURE["NO_HELMET_PER_RIDER"]
        violations_detected.append(
            (f"Riding Without Helmet ({without_helmet_count} Rider{'s' if without_helmet_count > 1 else ''}) - Sec 129/194D M.V. Act", fine_amount)
        )
        total_fine += fine_amount

    # 3. Format e-Challan Receipt
    divider = "=" * 60
    sub_divider = "-" * 60

    receipt_lines = [
        divider,
        "    ACADEMIC RESEARCH DEMONSTRATION E-CHALLAN REPORT",
        "  [ NOT AN OFFICIAL GOVERNMENT NOTICE • SIMULATION ONLY ]",
        divider,
        f"Challan Reference ID: {challan_id}",
        f"Date & Time        : {timestamp}",
        f"Vehicle Number     : {plate_number}",
        f"Location           : {location}",
        f"Riders Detected    : {person_count} (Unhelmeted: {without_helmet_count})",
        sub_divider,
        "VIOLATIONS CHARGED :"
    ]

    if violations_detected:
        for idx, (violation, cost) in enumerate(violations_detected, start=1):
            receipt_lines.append(f" {idx}. {violation:<42} : Rs {cost:>5}")
    else:
        receipt_lines.append(" None (No Violations Recorded)")

    receipt_lines.extend([
        sub_divider,
        f"TOTAL SIMULATED FINE: Rs {total_fine}",
        f"EVIDENCE SAVED      : {output_image_path}",
        divider,
        "DISCLAIMER: Generated by TwoWheelerViolationAI for academic",
        "evaluation. No financial transactions or legal obligations.",
        divider
    ])

    challan_text = "\n".join(receipt_lines)
    print("\n" + challan_text + "\n")

    log_filename = None
    pdf_filename = None

    # 4. Save e-Challan to Text Log
    if save_receipt and violations_detected:
        os.makedirs("challans", exist_ok=True)
        log_filename = f"challans/{challan_id}_{plate_number}.txt"
        with open(log_filename, "w", encoding="utf-8") as f:
            f.write(challan_text)
        print(f"Text receipt saved to -> {log_filename}")

    # 5. Generate and Save PDF Report
    if generate_pdf and violations_detected:
        try:
            from pdf_challan_generator import generate_pdf_challan
            reports_dir = os.path.join("challans", "pdf_reports")
            os.makedirs(reports_dir, exist_ok=True)
            pdf_filename = os.path.join(reports_dir, f"{challan_id}_{plate_number}.pdf")

            pdf_record = {
                "challan_id": challan_id,
                "vehicle_plate": plate_number,
                "date_time": timestamp,
                "location": location,
                "rider_count": person_count,
                "unhelmeted_count": without_helmet_count,
                "triple_riding": (person_count >= 3),
                "helmet_violation": (without_helmet_count > 0),
                "total_fine": total_fine,
                "violations": violations_detected,
                "evidence_path": output_image_path,
                "plate_crop": plate_crop_path,
                "audit_status": "VERIFIED" if plate_number not in ["UNKNOWN", "PLATE_NOT_DETECTED"] else "REVIEW_REQUIRED"
            }
            generate_pdf_challan(pdf_record, output_path=pdf_filename, save_copy=True)
            print(f"PDF report saved to -> {pdf_filename}")
        except Exception as e:
            print(f"[PDF Warning] Could not generate PDF report: {e}")

    return {
        "challan_id": challan_id,
        "plate_number": plate_number,
        "total_fine": total_fine,
        "violations": violations_detected,
        "receipt_path": log_filename,
        "pdf_path": pdf_filename
    }


